package modgen

import (
	"encoding/json"
	"fmt"
	"strings"

	"github.com/taumatix/claude-mods-go/mods"
)

// Transport selects how the shim reaches the Go program.
type Transport string

const (
	// Auto starts a daemon and falls back to one-shot if it cannot.
	Auto Transport = "auto"
	// Daemon keeps one Go process for the session and talks to it over loopback HTTP.
	Daemon Transport = "daemon"
	// Once starts the Go program for every step and replays a journal.
	Once Transport = "once"
)

// Valid reports whether t is a known transport.
func (t Transport) Valid() bool { return t == Auto || t == Daemon || t == Once }

var noArgs = map[mods.Method]bool{
	mods.UIPanes: true, mods.UISelection: true, mods.CommandList: true, mods.ToolList: true, mods.AgentList: true,
	mods.SessionCwd: true, mods.SessionRoot: true, mods.SessionModel: true, mods.SessionTurns: true,
	mods.SessionID: true, mods.SessionRepo: true, mods.SessionSurfaces: true, mods.SessionUsage: true,
	mods.SessionVersion: true, mods.ConfigList: true, mods.StoreKeys: true, mods.ClockNow: true,
	mods.PromptRead: true,
}

func arity(m mods.Method) int {
	switch {
	case noArgs[m]:
		return 0
	case m == mods.MCPCall:
		return 3
	}
	return 2
}

func js(v any) string {
	b, err := json.Marshal(v)
	if err != nil {
		panic(err)
	}
	return string(b)
}

// renderShim returns the hooks module. Claude Code's validator forbids passing
// `$` anywhere, so every call on it sits inside the handler that received it:
// each hook gets its own copy of the bridge, written out with literal
// `$.noun.method(` calls, for the declared methods plus what the transport needs.
func renderShim(m mods.Manifest, t Transport, targets []Target) string {
	var b strings.Builder
	w := func(format string, a ...any) { fmt.Fprintf(&b, format, a...) }

	w("// Generated by modgo. Do not edit: rebuild with `modgo build`.\n")
	w("const MOD = %s\n", js(m.Name))
	w("const TARGETS = %s\n", js(targetKeys(targets)))
	w("const HERE = decodeURIComponent(import.meta.url.replace(/^file:\\/\\//, '')).replace(/[^/]*$/, '')\n")
	w("const ROOT = HERE.replace(/hooks\\/$/, '')\n")
	w("let daemon = null\nlet uname = null\nlet useOnce = false\n\n")
	w("%s\n", randomToken)

	var cases strings.Builder
	for _, u := range m.Uses {
		fmt.Fprintf(&cases, "      case %s: return await $.%s(%s)\n", js(string(u)), u, args(arity(u)))
	}
	body := strings.NewReplacer(
		"/*BINARY*/", binarySrc(len(targets) == 1),
		"/*DAEMON*/", pick(t != Once, daemonSrc),
		"/*ONCE*/", pick(t != Daemon, onceSrc),
		"/*OPEN*/", openSrc(t),
		"/*CASES*/", cases.String(),
	).Replace(handlerSrc)

	w("export function register(on, options) {\n")
	for i, h := range m.Hooks {
		fn := strings.NewReplacer("/*REG*/", fmt.Sprint(i), "/*EVENT*/", js(h.Event)).Replace(body)
		if len(h.Match) > 0 {
			w("  on(%s, %s, async ($, e, next) => {\n%s  })\n", js(h.Event), js(h.Match), fn)
		} else {
			w("  on(%s, async ($, e, next) => {\n%s  })\n", js(h.Event), fn)
		}
	}
	w("}\n")
	return b.String()
}

func pick(ok bool, s string) string {
	if ok {
		return s
	}
	return ""
}

func args(n int) string {
	parts := make([]string, n)
	for i := range parts {
		parts[i] = fmt.Sprintf("a[%d]", i)
	}
	return strings.Join(parts, ", ")
}

func targetKeys(ts []Target) []string {
	out := make([]string, len(ts))
	for i, t := range ts {
		out[i] = t.OS + "-" + t.Arch
	}
	return out
}

func binarySrc(single bool) string {
	if single {
		return "    const binary = async () => ROOT + 'bin/' + TARGETS[0] + '/' + MOD\n"
	}
	return `    const binary = async () => {
      if (!uname) {
        const r = await $.process.run(['uname', '-sm'])
        const [s, a] = r.stdout.trim().split(/\s+/)
        uname = s.toLowerCase() + '-' + ({ x86_64: 'amd64', aarch64: 'arm64' }[a] || a)
      }
      if (!TARGETS.includes(uname)) throw new Error(MOD + ': no build for ' + uname + ' (have ' + TARGETS.join(', ') + ')')
      return ROOT + 'bin/' + uname + '/' + MOD
    }
`
}

func openSrc(t Transport) string {
	switch t {
	case Daemon:
		return "    const open = openDaemon\n"
	case Once:
		return "    const open = openOnce\n"
	}
	return `    const open = async (start) => {
      if (!useOnce) {
        try { return await openDaemon(start) } catch (err) { if (err && err.modgo) throw err; useOnce = true }
      }
      return openOnce(start)
    }
`
}

const randomToken = `function randomToken() {
  const a = new Uint8Array(32)
  if (typeof crypto !== 'undefined' && crypto.getRandomValues) crypto.getRandomValues(a)
  else for (let i = 0; i < a.length; i++) a[i] = Math.floor(Math.random() * 256)
  return Array.from(a, (v) => v.toString(16).padStart(2, '0')).join('')
}
`

const handlerSrc = `/*BINARY*/    const bridge = async (method, a) => {
      switch (method) {
/*CASES*/        default: throw new Error(MOD + ': ' + method + ' is not bridged by this mod')
      }
    }
/*DAEMON*//*ONCE*//*OPEN*/    const run = await open({ reg: /*REG*/, event: /*EVENT*/, e })
    let step = run.first
    let passed = false
    let last
    for (;;) {
      if (step.op === 'done') {
        if (step.value === null || step.value === undefined) return passed ? last : next(e)
        return step.value
      }
      if (step.op === 'error') throw new Error(MOD + ': ' + step.message)
      let res
      try {
        let value
        if (step.op === 'next') { value = await next(step.e); passed = true; last = value }
        else value = await bridge(step.method, step.args || [])
        res = { ok: true, value: value === undefined ? null : value }
      } catch (err) {
        res = { ok: false, error: String((err && err.message) || err) }
      }
      step = await run.resume(step, res)
    }
`

const daemonSrc = `    const post = async (d, path, body) => {
      const r = await $.http.fetch(d.base + path, {
        method: 'POST',
        headers: { authorization: 'Bearer ' + d.token, 'content-type': 'application/json' },
        body: JSON.stringify(body),
      })
      if (!r.ok) {
        const err = new Error(MOD + ': daemon ' + path + ' answered ' + r.status + ': ' + r.text.trim())
        err.status = r.status
        throw err
      }
      return JSON.parse(r.text)
    }
    const startDaemon = async () => {
      const bin = await binary()
      const token = randomToken()
      const handle = await $.process.spawn({ argv: [bin, 'serve'], env: { MODGO_TOKEN: token } })
      const it = handle[Symbol.asyncIterator]()
      let seen = ''
      for (;;) {
        const r = await it.next()
        if (r.done) throw new Error(MOD + ': daemon exited before listening: ' + seen.trim())
        seen += r.value.text
        const m = /LISTEN (\S+)/.exec(seen)
        if (m) {
          const d = { base: 'http://' + m[1], token }
          const gone = () => { if (daemon && daemon.d === d) daemon = null }
          handle.result.then(gone, gone)
          return d
        }
      }
    }
    const openDaemon = async (start) => {
      for (let attempt = 0; ; attempt++) {
        if (!daemon) {
          const p = startDaemon().then((d) => ({ d }))
          daemon = p
          p.catch(() => { if (daemon === p) daemon = null })
        }
        try {
          const d = (await daemon).d
          const first = await post(d, '/start', start)
          return { first, resume: (step, res) => post(d, '/resume', { run: first.run, cid: step.cid, ok: res.ok, value: res.value, error: res.error }) }
        } catch (err) {
          daemon = null
          if (attempt === 0 && !(err && err.status)) continue
          err.modgo = !!(err && err.status)
          throw err
        }
      }
    }
`

const onceSrc = `    const onceStep = async (start) => {
      const bin = await binary()
      const r = await $.process.run([bin, 'once'], { stdin: JSON.stringify(start) })
      if (r.exitCode !== 0) throw new Error(MOD + ': ' + (r.stderr.trim() || 'exit ' + r.exitCode))
      return JSON.parse(r.stdout)
    }
    const openOnce = async (start) => {
      const journal = []
      const first = await onceStep({ ...start, journal })
      return {
        first,
        resume: (step, res) => {
          journal.push({ op: step.op, method: step.method || 'next', ok: res.ok, value: res.value, error: res.error })
          return onceStep({ ...start, journal })
        },
      }
    }
`
